#!/usr/bin/env python3
"""Extract M4-S5 bitcount tables from the C probe into Rust source.

Usage: extract_bitcount_tables.py [--rom PATH] [--out PATH] <bctables-txt>   (repo root)

Options (all CWD-relative defaults, preserved for repo-root runs):
  --rom PATH   FDK ROM source (default: cpp/libAACenc/src/aacEnc_rom.cpp)
  --out PATH   output Rust file (default: rust/src/aac_enc/bitcount_tables.rs)

Reads the BCTABLES blocks of <bctables-txt> (produced by bitcount_probe,
which prints the exact integers the reference build uses) and writes
rust/src/aac_enc/bitcount_tables.rs. Run `cargo fmt` afterwards: like
extract_tables.py, this script emits fixed chunking and relies on
rustfmt for final layout (the committed file is script output +
rustfmt).

Every value is cross-checked against an INDEPENDENT parse of the C++
source text (cpp/libAACenc/src/aacEnc_rom.cpp): all eight tables are
plain hex/decimal integer initializers, so source text is exact.
Any mismatch aborts: tables are data, never hand-transcribed.
"""
import re
import sys

BCT = None
ROM = "cpp/libAACenc/src/aacEnc_rom.cpp"
OUT = "rust/src/aac_enc/bitcount_tables.rs"

_ARGS = sys.argv[1:]
while _ARGS and _ARGS[0].startswith("--"):
    _opt = _ARGS[0]
    if _opt in ("--rom", "--out"):
        if len(_ARGS) < 2:
            raise SystemExit(
                "usage: extract_bitcount_tables.py [--rom PATH] [--out PATH] "
                "<bctables-txt>   (repo root)")
        if _opt == "--rom":
            ROM = _ARGS[1]
        else:
            OUT = _ARGS[1]
        _ARGS = _ARGS[2:]
    elif _opt.startswith("--rom="):
        ROM = _opt[len("--rom="):]
        _ARGS = _ARGS[1:]
    elif _opt.startswith("--out="):
        OUT = _opt[len("--out="):]
        _ARGS = _ARGS[1:]
    else:
        raise SystemExit(f"unknown flag {_opt}; usage: extract_bitcount_tables.py "
                         f"[--rom PATH] [--out PATH] <bctables-txt>   (repo root)")
if len(_ARGS) != 1:
    raise SystemExit("usage: extract_bitcount_tables.py [--rom PATH] [--out PATH] "
                     "<bctables-txt>   (repo root)")
BCT = _ARGS[0]

txt = open(BCT).read().splitlines()


def ints(tag):
    for ln in txt:
        if ln.startswith(tag + " ") or ln == tag:
            return [int(x) for x in ln.split()[1:]]
    raise AssertionError(f"block {tag} missing")


# ---- probe values (lengths pin the table shapes) ----
spec = [
    ("LTAB12", "FDKaacEnc_huff_ltab1_2", 81, "u32"),
    ("LTAB34", "FDKaacEnc_huff_ltab3_4", 81, "u32"),
    ("LTAB56", "FDKaacEnc_huff_ltab5_6", 81, "u32"),
    ("LTAB78", "FDKaacEnc_huff_ltab7_8", 64, "u32"),
    ("LTAB910", "FDKaacEnc_huff_ltab9_10", 169, "u32"),
    ("LTAB11", "FDKaacEnc_huff_ltab11", 289, "u8"),
    ("SITABLONG", "FDKaacEnc_sideInfoTabLong", 52, "i16"),
    ("SITABSHORT", "FDKaacEnc_sideInfoTabShort", 16, "i16"),
]
probe = {}
for tag, _, n, _ in spec:
    probe[tag] = ints(tag)
    assert len(probe[tag]) == n, f"{tag}: got {len(probe[tag])}, want {n}"

# ---- independent parse from source text ----
rom = open(ROM).read()


def get_body(name):
    m = re.search(name + r"\s*(\[[^\]]*\]\s*)+=\s*\{([^;]*)\};", rom, re.S)
    assert m, f"{name} not found"
    return m.group(2)


def rom_ints(name):
    body = get_body(name)
    return [int(x, 0) for x in re.findall(r"0[xX][0-9a-fA-F]+|\d+", body)]


for tag, name, n, _ in spec:
    vals = rom_ints(name)
    assert len(vals) == n, f"{name}: got {len(vals)}, want {n}"
    assert vals == probe[tag], f"{name}: probe/source mismatch"


def rust_name(tag):
    return {
        "LTAB12": "HUFF_LTAB1_2",
        "LTAB34": "HUFF_LTAB3_4",
        "LTAB56": "HUFF_LTAB5_6",
        "LTAB78": "HUFF_LTAB7_8",
        "LTAB910": "HUFF_LTAB9_10",
        "LTAB11": "HUFF_LTAB11",
        "SITABLONG": "SIDE_INFO_TAB_LONG",
        "SITABSHORT": "SIDE_INFO_TAB_SHORT",
    }[tag]


def rust_type(tag):
    return {"u32": "u32", "u8": "u8", "i16": "i16"}[
        [t for g, _, _, t in spec if g == tag][0]
    ]


def chunks(vals, per_row):
    return [vals[i:i + per_row] for i in range(0, len(vals), per_row)]


with open(OUT, "w") as f:
    f.write("""/* -----------------------------------------------------------------------------
Software License for The Fraunhofer FDK AAC Codec Library for Android

(c) Copyright 2026 Fraunhofer-Gesellschaft zur Foerderung der angewandten
Forschung e.V. All rights reserved.

Generated by tools/enc-oracle/extract_bitcount_tables.py from the
bitcount_probe output, cross-checked value-for-value against
cpp/libAACenc/src/aacEnc_rom.cpp. Do not hand-edit: tables are data.
----------------------------------------------------------------------------- */
//! M4-S5 Huffman length tables and side-info tables
//! (`aacEnc_rom.h:122-128,167-168`), script-extracted.
""")
    # 4-D tables keep C index order [a][b][c][d], flattened row-major.
    f.write("""
/// `FDKaacEnc_huff_ltab1_2[3][3][3][3]` (ULONG, HI=book1 LO=book2).
pub(crate) const HUFF_LTAB1_2: [u32; 81] = [\n""")
    for row in chunks(probe["LTAB12"], 9):
        f.write("    " + ", ".join(f"0x{v:08x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_huff_ltab3_4[3][3][3][3]` (ULONG, HI=book3 LO=book4).
pub(crate) const HUFF_LTAB3_4: [u32; 81] = [\n""")
    for row in chunks(probe["LTAB34"], 9):
        f.write("    " + ", ".join(f"0x{v:08x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_huff_ltab5_6[9][9]` (ULONG, HI=book5 LO=book6).
pub(crate) const HUFF_LTAB5_6: [u32; 81] = [\n""")
    for row in chunks(probe["LTAB56"], 9):
        f.write("    " + ", ".join(f"0x{v:08x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_huff_ltab7_8[8][8]` (ULONG, HI=book7 LO=book8).
pub(crate) const HUFF_LTAB7_8: [u32; 64] = [\n""")
    for row in chunks(probe["LTAB78"], 8):
        f.write("    " + ", ".join(f"0x{v:08x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_huff_ltab9_10[13][13]` (ULONG, HI=book9 LO=book10).
pub(crate) const HUFF_LTAB9_10: [u32; 169] = [\n""")
    for row in chunks(probe["LTAB910"], 13):
        f.write("    " + ", ".join(f"0x{v:08x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_huff_ltab11[17][17]` (UCHAR, book 11 + ESC base).
pub(crate) const HUFF_LTAB11: [u8; 289] = [\n""")
    for row in chunks(probe["LTAB11"], 17):
        f.write("    " + ", ".join(f"0x{v:02x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_sideInfoTabLong` (52 entries, indexed by section SFB count).
pub(crate) const SIDE_INFO_TAB_LONG: [i16; 52] = [\n""")
    for row in chunks(probe["SITABLONG"], 13):
        f.write("    " + ", ".join(f"0x{v:04x}" for v in row) + ",\n")
    f.write("];\n")
    f.write("""
/// `FDKaacEnc_sideInfoTabShort` (16 entries, indexed by section SFB count).
pub(crate) const SIDE_INFO_TAB_SHORT: [i16; 16] = [\n""")
    for row in chunks(probe["SITABSHORT"], 8):
        f.write("    " + ", ".join(f"0x{v:04x}" for v in row) + ",\n")
    f.write("];\n")
print(f"wrote {OUT}")
