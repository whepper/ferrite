#!/usr/bin/env python3
"""Deterministic PCM fixtures for the M2 encoder oracle and Rust tests.

All files: 16-bit PCM WAV, 48 kHz. No randomness. Regenerating this script
must produce byte-identical output (fixed amplitudes/phases, no dither).
"""
import wave
import struct
import math
import os
import sys

SR = 48000

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))


def write_wav(name, channels, seconds, fn):
    n = int(SR * seconds)
    path = os.path.join(OUT, name)
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(2)
        w.setframerate(SR)
        frames = bytearray()
        for i in range(n):
            t = i / SR
            for c in range(channels):
                v = max(-32768, min(32767, int(fn(t, c, i))))
                frames += struct.pack("<h", v)
        w.writeframes(bytes(frames))
    print(f"wrote {path} ({n} samples/ch)")


def sine(t, f=1000.0, amp=10000.0):
    return amp * math.sin(2.0 * math.pi * f * t)


HALF = 24000  # sample index of the 0.5 s boundary

# Sharp onset: silence, then 1 kHz sine at full amplitude.
write_wav(
    "m2-onset-stereo-48k.wav", 2, 1.0,
    lambda t, c, i: 0.0 if i < HALF else sine(t),
)

# Sharp offset: 1 kHz sine, then silence.
write_wav(
    "m2-stepdown-stereo-48k.wav", 2, 1.0,
    lambda t, c, i: sine(t) if i < HALF else 0.0,
)

# Single full-scale click on top of a sine (click at sample 12000, mono).
CLICK = 12000
write_wav(
    "m2-click-mono-48k.wav", 1, 0.5,
    lambda t, c, i: 30000.0 if i == CLICK else sine(t, amp=8000.0),
)

# Edge attack: single impulse late in frame 3 (offset 900, window 7) then
# silence. Exercises the cross-border attack repeat
# (block_switch.cpp) which extends the SHORT sequence by one frame.
EDGE = 3 * 1024 + 900
write_wav(
    "m2-edge-mono-48k.wav", 1, 0.25,
    lambda t, c, i: 30000.0 if i == EDGE else 0.0,
)

# M1 fixtures, regenerated byte-identically for oracle runs.
write_wav("m2-silence-stereo-48k.wav", 2, 1.0, lambda t, c, i: 0.0)
write_wav("m2-sine-stereo-48k.wav", 2, 1.0, lambda t, c, i: sine(t))
write_wav(
    "m2-impulse-mono-48k.wav", 1, 0.2,
    lambda t, c, i: 30000.0 if abs(t - 0.1) < 1.0 / 96000 else 0.0,
)

# --- M3 fixtures ---

def multitone(t, c, i):
    return (sine(t, f=200.0, amp=6000.0) + sine(t, f=2000.0, amp=4000.0)
            + sine(t, f=8000.0, amp=2000.0))


write_wav("m3-multitone-stereo-48k.wav", 2, 1.0, multitone)


def sweep(t, c, i):
    # Linear chirp 100 Hz -> 15 kHz over 1 s, constant amplitude.
    f0, f1, dur = 100.0, 15000.0, 1.0
    phase = 2.0 * math.pi * (f0 * t + (f1 - f0) * t * t / (2.0 * dur))
    return 8000.0 * math.sin(phase)


write_wav("m3-sweep-stereo-48k.wav", 2, 1.0, sweep)


def splitmix32(state):
    state = (state + 0x9E3779B9) & 0xFFFFFFFF
    z = state
    z = ((z ^ (z >> 16)) * 0x21F0AAAD) & 0xFFFFFFFF
    z = ((z ^ (z >> 15)) * 0x735A2D97) & 0xFFFFFFFF
    z = z ^ (z >> 15)
    return state, z


NOISE_LEN = int(SR * 0.5)
_noise = []
_st = 0x12345678
for _ in range(NOISE_LEN):
    _st, z = splitmix32(_st)
    _noise.append((z % 16001) - 8000.0)
write_wav("m3-noise-mono-48k.wav", 1, 0.5, lambda t, c, i: _noise[i])


def tonal_noise(t, c, i):
    return sine(t, amp=8000.0) + _noise[i % NOISE_LEN] * 1500.0 / 8000.0


write_wav("m3-tonal-noise-stereo-48k.wav", 2, 0.5, tonal_noise)
write_wav("m3-quiet-sine-stereo-48k.wav", 2, 1.0,
          lambda t, c, i: sine(t, amp=50.0))

# F6 stress (M4-S6): full-scale deterministic PRNG + tone stack, stereo.
# Goal: loud HF-heavy content that overflows MAX_QUANT at the S4 gains
# (forcing >=1 gain-loop retry) and pressures the MIN_BUFSIZE element cap.
# Same splitmix32 stream family as the M3 noise (different seed), plus
# three full-scale sines; all amplitudes fixed, no dither.
_stress_st = 0x76F1A9B3
_stress_noise = []
for _ in range(int(SR * 0.5)):
    _stress_st, z = splitmix32(_stress_st)
    _stress_noise.append((z % 32767) - 16383.0)


def stress(t, c, i):
    nz = _stress_noise[i % len(_stress_noise)]
    tones = (12000.0 * math.sin(2.0 * math.pi * 6000.0 * t) +
             9000.0 * math.sin(2.0 * math.pi * 12000.0 * t) +
             6000.0 * math.sin(2.0 * math.pi * 18000.0 * t))
    return nz * 0.9 + tones


write_wav("m6-stress-stereo-48k.wav", 2, 0.5, stress)

# 44.1 kHz variants (different SFB table: same counts, different widths).
SR441 = 44100


def write_wav_sr(name, sr, channels, seconds, fn):
    n = int(sr * seconds)
    path = os.path.join(OUT, name)
    with wave.open(path, "wb") as w:
        w.setnchannels(channels)
        w.setsampwidth(2)
        w.setframerate(sr)
        frames = bytearray()
        for i in range(n):
            t = i / sr
            for c in range(channels):
                v = max(-32768, min(32767, int(fn(t, c, i))))
                frames += struct.pack("<h", v)
        w.writeframes(bytes(frames))
    print(f"wrote {path} ({n} samples/ch)")


def sine44(t, f=1000.0, amp=10000.0):
    return amp * math.sin(2.0 * math.pi * f * t)


write_wav_sr("m3-sine-stereo-441k.wav", SR441, 2, 1.0,
             lambda t, c, i: sine44(t))
write_wav_sr("m3-onset-stereo-441k.wav", SR441, 2, 1.0,
             lambda t, c, i: 0.0 if i < 22050 else sine44(t))
